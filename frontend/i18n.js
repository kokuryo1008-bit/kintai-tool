/* 現在の言語（localStorageから復元、デフォルトは日本語） */
let _currentLang = localStorage.getItem('kintai_lang') || 'ja';

/* 翻訳関数 */
function _t(key) {
  return (I18N[_currentLang] && I18N[_currentLang][key]) || (I18N.ja[key] || key);
}

/* 言語切替 */
function setLang(lang) {
  if (!I18N[lang]) return;
  _currentLang = lang;
  localStorage.setItem('kintai_lang', lang);
  _applyI18n();
  // ページ固有の動的テキスト再描画（定義されていれば呼ぶ）
  if (typeof _refreshDynamicText === 'function') _refreshDynamicText();
}

/* data-i18n 属性を持つ要素を一括翻訳 */
function _applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = _t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    el.placeholder = _t(el.dataset.i18nPh);
  });
  /* 言語ボタンのアクティブ状態 */
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.style.fontWeight = btn.dataset.lang === _currentLang ? '800' : '400';
    btn.style.opacity    = btn.dataset.lang === _currentLang ? '1' : '0.5';
  });
  document.documentElement.lang =
    _currentLang === 'zh' ? 'zh-CN' : _currentLang;
}

/* ステータスラベル（employee.js から使用） */
function _statusLabel(s) {
  return { pending: _t('status_pending'), approved: _t('status_approved'), rejected: _t('status_rejected') }[s] || s;
}

/* DOMContentLoaded 後に適用 */
document.addEventListener('DOMContentLoaded', _applyI18n);
